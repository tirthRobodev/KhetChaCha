  /// Returns popular products to display on the default screen
  static List<FarmProduct> get popularProducts =>
      allProducts.where((p) => p.isPopular).toList();

  /// Returns products filtered by category ('all', 'crops', 'vegetables', 'fruits', 'flowers')
  static List<FarmProduct> getProductsByCategory(String category) {
    if (category == 'all') {
      return popularProducts;
    }
    return allProducts.where((p) => p.category == category).toList();
  }

  /// Live search across English and all regional translations
  static List<FarmProduct> search(String query, {String? category}) {
    final clean = query.trim().toLowerCase();
    var list = category == null || category == 'all'
        ? allProducts
        : allProducts.where((p) => p.category == category).toList();

    if (clean.isEmpty) return list;

    return list.where((p) {
      if (p.englishName.toLowerCase().contains(clean)) return true;
      for (final val in p.translations.values) {
        if (val.toLowerCase().contains(clean)) return true;
      }
      return false;
    }).toList();
  }

  /// Finds a product by its ID or returns a default
  static FarmProduct? findById(String id) {
    try {
      return allProducts.firstWhere((p) => p.id == id);
    } catch (_) {
      return null;
    }
  }

  /// Helper to get crops recommended for a given state
  static List<FarmProduct> getRecommendedForState(String stateName) {
    final cleanState = stateName.trim().toLowerCase();
    return allProducts.where((p) {
      return p.recommendedStates.any((s) => s.toLowerCase() == cleanState);
    }).toList();
  }
